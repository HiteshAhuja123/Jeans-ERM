import type { Order, OrderItemSizeQty, OrderLineItem } from "@/types";

const sizeIdByCode: Record<string, string> = {
  "28": "size-001",
  "30": "size-002",
  "32": "size-003",
  "34": "size-004",
  "36": "size-005",
  "38": "size-006",
};

function breakdown(qtys: Record<string, number>): OrderItemSizeQty[] {
  return Object.entries(qtys).map(([code, quantity]) => ({ sizeId: sizeIdByCode[code], quantity }));
}

function total(sizes: OrderItemSizeQty[]): number {
  return sizes.reduce((sum, entry) => sum + entry.quantity, 0);
}

function item(
  id: string,
  styleId: string,
  styleCode: string,
  styleName: string,
  colorId: string,
  colorName: string,
  qtys: Record<string, number>,
): OrderLineItem {
  const sizeBreakdown = breakdown(qtys);
  return {
    id,
    styleId,
    styleCode,
    styleName,
    colorId,
    colorName,
    sizeBreakdown,
    quantity: total(sizeBreakdown),
    unit: "pcs",
  };
}

