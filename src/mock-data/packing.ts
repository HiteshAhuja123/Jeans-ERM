function makeCartons(packingOrderId: string, packingEntryId: string, cartonNumberPrefix: string, count: number, perCarton: number, createdDate: string): PackingCarton[] {
  return Array.from({ length: count }, (_, i) => ({
    id: `${packingEntryId}-c${String(i + 1).padStart(3, "0")}`,
    packingOrderId,
    packingEntryId,
    cartonNumber: `${cartonNumberPrefix}-C${String(i + 1).padStart(3, "0")}`,
    quantity: perCarton,
    createdDate,
  }));
}

